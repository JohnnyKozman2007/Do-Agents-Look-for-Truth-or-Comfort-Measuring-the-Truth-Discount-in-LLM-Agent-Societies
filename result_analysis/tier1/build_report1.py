"""Render the Tier 1 (judge and label quality) results into one self-contained HTML file."""
from datetime import datetime
from html import escape

from report_blocks import render_blocks
from styles import CSS


def caveats(judge_name, has_reference, synthetic=False):
    """Reading guide for the Tier 1 metrics."""
    cav = [
        f"Labels come from <b>{escape(judge_name)}</b>, produced by a separate workflow; this report only analyzes them. It makes no model calls.",
        "The GO/SKIP log is the only ground truth available at scale: a listener who paid to check read the board. It validates the CHECKED labels, not the soft belief labels (FACT, UNCERTAIN, SKEPTICAL).",
        ("Agreement with the reference labels is computed on the overlap only; the reference is not necessarily correct."
         if has_reference else "No reference labels were supplied, so agreement (kappa) with a human audit or a second judge is not in this report."),
        "Placebo and permutation tests treat the twin pair as the unit and swap twins within pairs; bootstrap intervals resample twin pairs.",
        "Scoring sensitivity compares signs and significance across scorings; magnitudes are not comparable across scales.",
    ]
    if synthetic:
        cav.insert(0, "<b>SYNTHETIC PLACEHOLDER LABELS.</b> These labels are random and exist only to test the code. Nothing below is a result.")
    return cav


def build(results, d, data_dirs, label_files, reference_files, judge_name, out_path, synthetic=False):
    kpis = [("Towns", f"{d.run_id.nunique():,}"), ("Listeners", f"{len(d):,}"), ("Labeled", f"{int(d.labeled.sum()):,} ({100 * d.labeled.mean():.0f}%)"),
            ("Omitted (NOT_MENTIONED)", f"{int(d.omitted.sum()):,}"), ("Reference labels", "yes" if reference_files else "none")]
    kpi_html = "".join(f'<div class="kpi"><b>{v}</b><span>{k}</span></div>' for k, v in kpis)
    nav = "".join(f'<a href="#{r["id"]}">{escape(r["title"].split(" - ")[0])}</a>' for r in results)
    secs = []
    for r in results:
        take = "".join(f"<li>{escape(s)}</li>" for s in r["summary"])
        secs.append(f'<h2 id="{r["id"]}">{escape(r["title"])}</h2><div class="card"><b>Key takeaways</b><ul class="take">{take}</ul></div>' + render_blocks(r["blocks"]))
    cav_html = "".join(f"<li>{c}</li>" for c in caveats(judge_name, bool(reference_files), synthetic))
    html = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Tier 1 Judge and Label Quality</title><style>{CSS}</style></head><body><div class="wrap">
<h1>Tier 1: Judge Validation and Label Quality</h1>
<p class="sub">Checks on the belief labels before any truth-discount claim. Generated {datetime.now():%Y-%m-%d %H:%M}. Data: <code>{escape(", ".join(str(x) for x in data_dirs))}</code>. Labels: <code>{escape(", ".join(str(x) for x in label_files))}</code>.</p>
<nav>{nav}</nav><div class="kpis">{kpi_html}</div>
<div class="card warn"><b>Read this first</b><ul class="take">{cav_html}</ul></div>
{"".join(secs)}
<footer>Generated by result_analysis/tier1/run_tier1.py</footer></div></body></html>"""
    with open(out_path, "w") as f:
        f.write(html)
    return out_path
